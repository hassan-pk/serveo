const { _electron: electron, expect } = require('@playwright/test');
const { mkdtempSync } = require('node:fs');
const { tmpdir } = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const data=mkdtempSync(path.join(tmpdir(),'serveo-images-'));
const env={...process.env,SERVEO_DATA_DIR:data};delete env.ELECTRON_RUN_AS_NODE;delete env.SERVEO_DEV_URL;
let app;
(async()=>{
 app=await electron.launch(process.env.SERVEO_TEST_EXECUTABLE?{executablePath:path.resolve(process.env.SERVEO_TEST_EXECUTABLE),args:[],env}:{args:[path.resolve('.')],env});
 const page=await app.firstWindow();
 await page.getByLabel('Shop name',{exact:true}).fill('Image review');
 await page.getByLabel('Your name',{exact:true}).fill('Reviewer');
 await page.getByLabel('Username',{exact:true}).fill('review');
 await page.getByLabel('Password',{exact:true}).fill('review-password');
 await page.getByRole('button',{name:'Create my shop'}).click();
 await page.getByRole('button',{name:'Menu & stock',exact:true}).click();
 await page.locator('[data-action="new-product"]').first().click();
 await page.getByLabel('Item name',{exact:true}).fill('Custom item');
 await page.getByLabel('Selling price',{exact:true}).fill('150');
 const upload=page.locator('input[name=productImage]');
 await upload.setInputFiles(path.resolve('src/renderer/assets/bbq.jpg'));
 await expect(page.locator('#product-image-error')).toContainText('Image ready');
 await page.screenshot({path:'test-results/product-image-editor.png'});
 await page.getByRole('button',{name:'Save menu item'}).click();
 await expect(page.locator('[role=dialog]')).toHaveCount(0);
 let snap=await page.evaluate(()=>window.serveo.snapshot());const first=snap.products[0].image;
 assert.ok(first.startsWith('data:image/jpeg;base64,'));
 await page.getByRole('button',{name:'New sale',exact:true}).click();
 await expect(page.locator('.product-card img')).toHaveAttribute('src',first);
 async function edit(){await page.getByRole('button',{name:'Menu & stock',exact:true}).click();await page.locator('[data-action^="product:"]').first().click();}
 await edit();
 await page.locator('input[name=productImage]').setInputFiles(path.resolve('src/renderer/assets/drinks.jpg'));
 await expect(page.locator('#product-image-error')).toContainText('Image ready');
 await page.getByRole('button',{name:'Save menu item'}).click();
 await expect(page.locator('[role=dialog]')).toHaveCount(0);
 snap=await page.evaluate(()=>window.serveo.snapshot());const replacement=snap.products[0].image;assert.notEqual(replacement,first);
 await page.reload();await edit();
 await expect(page.locator('#product-image-preview img')).toHaveAttribute('src',replacement);
 await page.getByRole('button',{name:'Remove image',exact:true}).click();
 await page.getByRole('button',{name:'Close dialog'}).click();
 assert.equal((await page.evaluate(()=>window.serveo.snapshot())).products[0].image,replacement);
 await edit();
 await page.locator('input[name=productImage]').setInputFiles({name:'bad.jpg',mimeType:'image/jpeg',buffer:Buffer.from('not an image')});
 await expect(page.locator('#product-image-error')).not.toContainText('Preparing');
 await expect(page.getByRole('button',{name:'Save menu item'})).toBeEnabled();
 await expect(page.locator('#product-image-preview img')).toHaveAttribute('src',replacement);
 await page.getByRole('button',{name:'Remove image',exact:true}).click();
 await page.getByRole('button',{name:'Save menu item'}).click();
 await expect(page.locator('[role=dialog]')).toHaveCount(0);
 await page.getByRole('button',{name:'New sale',exact:true}).click();
 await expect(page.locator('.product-card img')).toHaveCount(0);
 assert.equal((await page.evaluate(()=>window.serveo.snapshot())).products[0].image,'');
 console.log('Product images desktop passed: add, replace, reload, POS display, cancel removal, invalid upload, saved removal. Isolated data:',data);
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(app)await app.close();});
